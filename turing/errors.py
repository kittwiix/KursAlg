"""Исключения, которые может выбросить ядро машины Тьюринга.

Все ошибки наследуются от TuringError, поэтому интерфейсу достаточно поймать
одно исключение и показать его текст пользователю.
"""


class TuringError(Exception):
    """Общая ошибка ядра.

    От неё наследуются ошибки разбора программы и разбора ленты. Такой общий
    предок удобен интерфейсу: не нужно перечислять все виды исключений.
    """


class ProgramSyntaxError(TuringError):
    """Ошибка в тексте программы.

    Хранит номер строки, чтобы интерфейс мог подсветить именно то место,
    где пользователь допустил опечатку. Если номер равен нулю, ошибка
    относится ко всей программе целиком.
    """

    def __init__(self, line_number: int, message: str) -> None:
        """Запоминает номер строки и понятное описание ошибки."""
        self.line_number = line_number
        self.message = message
        super().__init__(str(self))

    def __str__(self) -> str:
        """Возвращает текст ошибки в виде «Строка 3: ...»."""
        if self.line_number > 0:
            return f"Строка {self.line_number}: {self.message}"
        return self.message


class TapeParseError(TuringError):
    """Ошибка в записи начальной ленты.

    Например, пользователь поставил два маркера головки или написал символ,
    который нельзя разместить в одной ячейке.
    """

    def __init__(self, message: str) -> None:
        """Сохраняет описание ошибки для показа в интерфейсе."""
        self.message = message
        super().__init__(message)


class StepLimitExceeded(TuringError):
    """Сообщение о срабатывании ограничителя шагов.

    Исключение используется в тестах и в консольных сценариях. В интерфейсе
    машина не выбрасывает его наружу, а переходит в состояние «лимит»,
    чтобы можно было спокойно показать журнал и итоговую ленту.
    """

    def __init__(self, limit: int) -> None:
        """Запоминает предельное число шагов."""
        self.limit = limit
        super().__init__(
            f"Достигнут лимит шагов ({limit}). Возможно, программа зациклилась."
        )
